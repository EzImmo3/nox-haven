import fs from 'node:fs';
import assert from 'node:assert/strict';
const app=fs.readFileSync('src/App.tsx','utf8');
const extra=fs.readFileSync('src/extraFeatures.tsx','utf8');
const types=fs.readFileSync('src/types.ts','utf8');
const data=fs.readFileSync('src/data.ts','utf8');
assert(types.includes("mode: 'flashcards' | 'quiz' | 'focus'"),'Le type de session doit reconnaître Deep Work.');
assert(types.includes('energyBefore?: number; energyAfter?: number; reflection?: string'),'Les métadonnées du bilan de concentration doivent être optionnelles.');
assert(data.includes("!['flashcards','quiz','focus'].includes(session.mode)"),'La sauvegarde doit accepter le mode focus.');
assert(data.includes("session.mode === 'focus' ? session.cardsReviewed !== 0 || session.correct !== 0"),'Une session focus ne doit pas être comptée comme une carte ou une bonne réponse.');
assert(extra.includes('setRemaining(duration*60)'),'Le timer doit démarrer avec la durée choisie.');
assert(extra.includes('setInterval(()=>setRemaining')&&extra.includes('setRemaining(value=>value===null?null:Math.max(0,value-1))'),'Le compte à rebours doit s’arrêter à zéro.');
assert(extra.includes("mode:'focus'")&&extra.includes('durationMinutes:duration'),'La session terminée doit être enregistrée avec la durée prévue.');
assert(extra.includes('Mettre en pause')&&extra.includes('Reprendre')&&extra.includes('Annuler'),'Les commandes du timer doivent être opérationnelles.');
assert(extra.includes('energyBefore,energyAfter,reflection'),'Le bilan doit enregistrer le ressenti et la réflexion.');
assert(app.includes("tab==='focus'&&<FocusStudio")&&app.includes("['focus','Focus & énergie',Timer]"),'L’espace Focus doit être accessible depuis la navigation.');
console.log('FOCUS & ÉNERGIE — 10/10 assertions réussies.');
